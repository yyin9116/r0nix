/**
 * 白板卡片 / 分组的调色板
 * ---------------------------------------------------------------------------
 * 这些颜色【刻意不随 UI 主题翻转】：白板是一张纸，卡片是纸上的便签，便签颜色属于
 * 内容语义（用户选的分类色），不是界面表面色。所以它们不走 --surface-* /
 * --content-* 令牌，而是自成一组常量。这也是它们至今不在 check-design-tokens
 * 扫描范围内的原因（那是给「界面样式」用的守卫）。
 *
 * 为什么抽成单一模块：这份数据原先在 WhiteboardCanvas.tsx（渲染画布用）与
 * Whiteboards.tsx（色板选择器用）各存了一份，而且**已经漂移** ——
 * 两处的 zinc.fill 分别是 `rgba(250,250,250,0.98)` 与 `rgba(250,250,250,0.96)`。
 * 后者那份除了 chip 与 border 之外根本没有消费者（选择器不读 fill / text），
 * 所以统一到 0.98 是零视觉变化的：0.96 那个值从来没被渲染过。
 *
 * ── 2026-10-04：五个色收敛为两个（zinc + blue） ──────────────────────────────
 *
 * 原配色是 zinc / stone / slate / olive / blue。收敛前先量了它们的感知可分辨度
 * （sRGB → OKLab，逐通道算 ΔE；脚本见 docs/design-system.md §3.6）：
 *
 *   | 通道                      | 五色最大成对 ΔE | 说明                     |
 *   |---------------------------|-----------------|--------------------------|
 *   | fill（纸面，占卡片绝大部分） | 0.0106          | 低于 JND —— 五色完全同色 |
 *   | chip（卡片头部条）          | 0.0328          | 刚过 JND                 |
 *   | border（1px 描边）         | 0.2469          | 唯一承载差异的通道        |
 *
 * 四个「中性色阶」的 border 色度（OKLab C）分别是 0.010 / 0.008 / 0.033 / 0.036，
 * 即**全是灰**，只是灰里掺了一丝暖 / 冷 / 橄榄色偏；明度极差 0.094。
 *
 * 结论：这不是一套「颜色分类系统」，而是「同一张近白纸上的一根 1px 描边色偏」。
 * 用户选了色，卡片本体（fill + chip）像素级不变 —— 属于伪选择，同时违反
 * §3.5 / §14 的「非 zinc 中性色阶 → 一个界面不能有两种灰」。
 *
 * 收敛后只剩两项，且是**语义两项**而非「同一色的四个色偏」：
 *   - `zinc`：常态纸面（论文卡、笔记卡、分组框）
 *   - `blue`：需要你注意的项（开放问题、来自阅读批注的卡片）
 * 二者 border ΔE = 0.2469，清晰可分。
 *
 * 迁移：旧值 stone / slate / olive 一律落回 zinc（见 LEGACY_CARD_COLORS）。
 * 这会让**已有白板**里原先用这三色的卡片变为 zinc —— 属可见变更，已接受。
 * 代价是种子模板里「问题陈述 / 方法证据」两张便签不再靠颜色区分，改由标题承载。
 * blue 保留：它色度 0.172，与四个中性有量级差异，是真正的第二档，不是色偏。
 */

/** 白板卡片可选的分类色。分组（group）也用同一组。 */
export type CardColor = "zinc" | "blue";

export type BoardSwatch = {
  /** 卡片描边；也用作色板选择器里的圆点 */
  border: string;
  /** 卡片填充（半透明，透出画布底纹） */
  fill: string;
  /** 卡片头部条与色板选择器按钮的底色 */
  chip: string;
  /** 卡片上的文字色（与 fill 成对，保证可读） */
  text: string;
};

/** 色板选择器的展示顺序。zinc 在前（默认档），blue 在后（强调档）。 */
export const BOARD_COLOR_ORDER: readonly CardColor[] = ["zinc", "blue"];

export const BOARD_PALETTE: Record<CardColor, BoardSwatch> = {
  zinc: { border: "rgba(63,63,70,0.9)", fill: "rgba(250,250,250,0.98)", chip: "rgba(82,82,91,0.12)", text: "#18181b" },
  blue: { border: "rgba(37,99,235,0.8)", fill: "rgba(248,250,252,0.98)", chip: "rgba(59,130,246,0.12)", text: "#172554" },
};

/**
 * 把任意来源的色值收敛到当前的 `CardColor`。
 *
 * 这是**唯一**的色值入口，三条读取路径都走它：已持久化的 localStorage 白板、
 * 手改过的数据、以及各 `create*Card` 的默认参数。
 *
 * 旧值 stone / slate / olive 不在返回值域里，会与未知值一起落回 `zinc`。
 * 不额外写一份「旧值清单」常量：那会是一个零消费者的导出（见 §14），
 * 而映射本身不需要逐项判断 —— 收敛后非 blue 即 zinc，没有第三种去向。
 */
export function normalizeCardColor(value: unknown): CardColor {
  return value === "blue" ? "blue" : "zinc";
}
